"use client";

import React, { useState } from "react";
import { ConceptNodeState } from "@/lib/api";

interface ConceptProgressStripProps {
  conceptGraph: ConceptNodeState[];
  activeConceptId: string;
  onSelectConcept?: (conceptId: string) => void;
}

export function ConceptProgressStrip({
  conceptGraph,
  activeConceptId,
  onSelectConcept,
}: ConceptProgressStripProps) {
  const [selectedNodeId, setSelectedNodeId] = useState<string | null>(null);

  if (!conceptGraph || conceptGraph.length === 0) {
    return null;
  }

  const selectedNode =
    conceptGraph.find((n) => n.concept_id === (selectedNodeId || activeConceptId)) ||
    conceptGraph[0];

  return (
    <div className="bg-white dark:bg-gray-900 border border-gray-200 dark:border-gray-800 rounded-2xl p-5 shadow-sm space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-gray-100 dark:border-gray-800 pb-3">
        <div>
          <h4 className="text-sm font-bold text-gray-900 dark:text-gray-100 flex items-center gap-2">
            <span>🧬</span>
            <span>Concept Dependency Graph (DAG)</span>
          </h4>
          <p className="text-[11px] text-gray-500 dark:text-gray-400 mt-0.5">
            Topological curriculum generated by Agent 1. Concepts unlock as prerequisites reach &ge; 75%.
          </p>
        </div>

        <div className="flex items-center gap-2 text-[10px] font-mono">
          <span className="flex items-center gap-1 text-emerald-600 dark:text-emerald-400">
            <span className="w-2 h-2 rounded-full bg-emerald-500"></span>
            Mastered (&ge;75%)
          </span>
          <span className="flex items-center gap-1 text-blue-600 dark:text-blue-400">
            <span className="w-2 h-2 rounded-full bg-blue-500"></span>
            Active
          </span>
          <span className="flex items-center gap-1 text-gray-400">
            <span className="w-2 h-2 rounded-full bg-gray-400"></span>
            Locked
          </span>
        </div>
      </div>

      {/* Horizontal Scrollable Progression Strip */}
      <div className="flex items-center gap-3 overflow-x-auto pb-2 scrollbar-thin">
        {conceptGraph.map((node, idx) => {
          const isActive = node.concept_id === activeConceptId;
          const isSelected = selectedNode?.concept_id === node.concept_id;
          const isMastered = node.status === "MASTERED" || node.mastery_rating >= 0.75;
          const isLocked = node.status === "LOCKED";

          return (
            <React.Fragment key={node.concept_id}>
              <button
                type="button"
                onClick={() => {
                  setSelectedNodeId(node.concept_id);
                  if (onSelectConcept) onSelectConcept(node.concept_id);
                }}
                className={`flex-shrink-0 text-left p-3 rounded-xl border transition relative min-w-[180px] max-w-[220px] ${
                  isSelected
                    ? "ring-2 ring-blue-500 border-blue-500 bg-blue-50/40 dark:bg-blue-950/40 shadow-sm"
                    : isMastered
                    ? "border-emerald-300 dark:border-emerald-800 bg-emerald-50/30 dark:bg-emerald-950/20 hover:bg-emerald-50"
                    : isActive
                    ? "border-blue-400 dark:border-blue-700 bg-blue-50/20 dark:bg-blue-950/30 hover:bg-blue-50/40"
                    : "border-gray-200 dark:border-gray-800 bg-gray-50/60 dark:bg-gray-800/40 opacity-75 hover:opacity-100"
                }`}
              >
                {/* Header Badge */}
                <div className="flex items-center justify-between gap-1 mb-1.5">
                  <span className="text-[10px] font-mono text-gray-400 font-bold">
                    #{idx + 1}
                  </span>
                  <span
                    className={`text-[9px] font-mono px-1.5 py-0.5 rounded font-bold uppercase ${
                      isMastered
                        ? "bg-emerald-100 text-emerald-800 dark:bg-emerald-900 dark:text-emerald-200"
                        : isActive
                        ? "bg-blue-100 text-blue-800 dark:bg-blue-900 dark:text-blue-200"
                        : "bg-gray-200 text-gray-700 dark:bg-gray-700 dark:text-gray-300"
                    }`}
                  >
                    {isMastered ? "🏆 Mastered" : isActive ? "⚡ Active" : "🔒 Locked"}
                  </span>
                </div>

                {/* Title */}
                <p className="text-xs font-semibold text-gray-900 dark:text-gray-100 truncate">
                  {node.title}
                </p>

                {/* Progress bar */}
                <div className="mt-2 space-y-1">
                  <div className="flex justify-between text-[10px] font-mono text-gray-500">
                    <span>Mastery</span>
                    <span>{(node.mastery_rating * 100).toFixed(0)}%</span>
                  </div>
                  <div className="w-full bg-gray-200 dark:bg-gray-700 h-1.5 rounded-full overflow-hidden">
                    <div
                      className={`h-full transition-all duration-500 rounded-full ${
                        isMastered
                          ? "bg-emerald-500"
                          : isActive
                          ? "bg-blue-500"
                          : "bg-gray-400"
                      }`}
                      style={{ width: `${Math.max(5, node.mastery_rating * 100)}%` }}
                    />
                  </div>
                </div>
              </button>

              {idx < conceptGraph.length - 1 && (
                <span className="text-gray-300 dark:text-gray-700 text-xs font-bold flex-shrink-0">
                  →
                </span>
              )}
            </React.Fragment>
          );
        })}
      </div>

      {/* Selected Node Details Drawer */}
      {selectedNode && (
        <div className="p-3 bg-gray-50 dark:bg-gray-800/60 border border-gray-200 dark:border-gray-800 rounded-xl text-xs space-y-1">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <span className="font-semibold text-gray-900 dark:text-gray-100">
              Focus: {selectedNode.title}
            </span>
            <span className="font-mono text-[10px] text-gray-400">
              ID: {selectedNode.concept_id}
            </span>
          </div>
          {selectedNode.summary_hook && (
            <p className="text-gray-600 dark:text-gray-300 italic text-[11px]">
              &ldquo;{selectedNode.summary_hook}&rdquo;
            </p>
          )}
          {selectedNode.prerequisites && selectedNode.prerequisites.length > 0 && (
            <div className="pt-1 text-[10px] text-gray-500 flex gap-1 items-center flex-wrap">
              <span className="font-semibold">Prerequisites:</span>
              {selectedNode.prerequisites.map((p) => (
                <span
                  key={p}
                  className="px-1.5 py-0.5 rounded bg-gray-200 dark:bg-gray-700 font-mono"
                >
                  {p}
                </span>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
